using System.Text;
using System.Text.Json;

namespace Vibe.UI.Tests.Theme;

/// <summary>
/// Turns the theme definitions in <c>themes/*.json</c> into the files that ship: the color
/// block of <c>vibe-base.css</c> and the palette table the theme service and the CLI read.
/// Those files are checked in. <see cref="ThemeGenerationTests"/> regenerates them and fails
/// when they differ, so a color can only change by changing its definition.
/// </summary>
internal static class ThemeArtifacts
{
    internal const string UpdateVariable = "UPDATE_GENERATED_THEMES";

    /// <summary>The definition that supplies the stylesheet's default colors.</summary>
    internal const string DefaultTheme = "default";

    internal const string StylesheetPath = "src/Vibe.UI/wwwroot/css/vibe-base.css";
    internal const string PaletteDataPath = "src/Vibe.UI/Services/Theme/ThemePaletteData.g.cs";

    internal static readonly string RegenerateCommand =
        $"{UpdateVariable}=true dotnet test tests/Vibe.UI.Tests --filter ThemeGeneration";

    internal sealed record ThemeDefinition(
        string Name,
        IReadOnlyList<KeyValuePair<string, string>> Light,
        IReadOnlyList<KeyValuePair<string, string>> Dark
    );

    internal static string RepositoryRoot()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "Vibe.slnx")))
        {
            directory = directory.Parent;
        }

        return directory?.FullName
            ?? throw new DirectoryNotFoundException(
                $"Could not find Vibe.slnx above '{AppContext.BaseDirectory}'."
            );
    }

    internal static string ReadRepositoryFile(string relativePath) =>
        Normalize(File.ReadAllText(Path.Combine(RepositoryRoot(), relativePath)));

    /// <summary>Every definition file, by file name without extension.</summary>
    internal static IReadOnlyDictionary<string, ThemeDefinition> LoadAll()
    {
        var directory = Path.Combine(RepositoryRoot(), "themes");

        return Directory
            .EnumerateFiles(directory, "*.json")
            .OrderBy(Path.GetFileNameWithoutExtension, StringComparer.Ordinal)
            .ToDictionary(
                file => Path.GetFileNameWithoutExtension(file),
                Load,
                StringComparer.Ordinal
            );
    }

    /// <summary>The selectable palettes: every definition except the stylesheet default.</summary>
    internal static IReadOnlyList<ThemeDefinition> LoadPalettes() =>
        LoadAll().Where(pair => pair.Key != DefaultTheme).Select(pair => pair.Value).ToArray();

    private static ThemeDefinition Load(string file)
    {
        using var document = JsonDocument.Parse(File.ReadAllText(file));
        var root = document.RootElement;

        // JsonDocument keeps properties in file order, which is the order tokens are written in.
        static KeyValuePair<string, string>[] Tokens(JsonElement mode) =>
            mode.EnumerateObject()
                .Select(token => new KeyValuePair<string, string>(
                    token.Name,
                    token.Value.GetString()!
                ))
                .ToArray();

        return new ThemeDefinition(
            root.GetProperty("name").GetString()!,
            Tokens(root.GetProperty("light")),
            Tokens(root.GetProperty("dark"))
        );
    }

    /// <summary>The C# palette table, as it should be on disk.</summary>
    internal static string RenderPaletteData(IReadOnlyList<ThemeDefinition> palettes)
    {
        var text = new StringBuilder();
        text.Append(
            $$"""
            // <auto-generated>
            //   Generated from themes/*.json. Do not edit by hand.
            //   To change a color, edit its definition, then run:
            //     {{RegenerateCommand}}
            // </auto-generated>
            #nullable enable

            using System.Collections.Generic;

            namespace Vibe.UI.Services.Theme;

            /// <summary>
            /// The built-in palettes, one list of token and value per mode. The theme service and
            /// the CLI both read this table, so there is one copy of every color.
            /// </summary>
            internal static class ThemePaletteData
            {
                /// <summary>The names accepted as a base color.</summary>
                internal static readonly string[] Names =
                [
                    {{string.Join(", ", palettes.Select(palette => $"\"{palette.Name}\""))}}
                ];

                /// <summary>
                /// The tokens for a palette in one mode, or null when the name is not a built-in palette.
                /// </summary>
                internal static KeyValuePair<string, string>[]? Find(string name, bool dark) => name switch
                {

            """
        );

        foreach (var palette in palettes)
        {
            text.Append(
                $"        \"{palette.Name}\" => dark ? {palette.Name}Dark : {palette.Name}Light,\n"
            );
        }

        text.Append("        _ => null\n    };\n");

        foreach (var palette in palettes)
        {
            AppendTokens(text, $"{palette.Name}Light", palette.Light);
            AppendTokens(text, $"{palette.Name}Dark", palette.Dark);
        }

        text.Append("}\n");
        return Normalize(text.ToString());
    }

    private static void AppendTokens(
        StringBuilder text,
        string field,
        IReadOnlyList<KeyValuePair<string, string>> tokens
    )
    {
        text.Append(
            $"\n    private static readonly KeyValuePair<string, string>[] {field} =\n    [\n"
        );
        foreach (var (name, value) in tokens)
        {
            text.Append($"        new(\"{name}\", \"{value}\"),\n");
        }

        text.Append("    ];\n");
    }

    /// <summary>The stylesheet with its two color blocks rewritten from the definition.</summary>
    internal static string RenderStylesheet(string stylesheet, ThemeDefinition definition)
    {
        var withLight = ReplaceBlock(stylesheet, "light", definition.Light);
        return ReplaceBlock(withLight, "dark", definition.Dark);
    }

    private static string ReplaceBlock(
        string stylesheet,
        string mode,
        IReadOnlyList<KeyValuePair<string, string>> tokens
    )
    {
        var start = $"  /* vibe:colors:{mode}:start */\n";
        var end = $"  /* vibe:colors:{mode}:end */";

        var from = stylesheet.IndexOf(start, StringComparison.Ordinal);
        var to = stylesheet.IndexOf(end, StringComparison.Ordinal);
        if (from < 0 || to < from)
        {
            throw new InvalidOperationException(
                $"{StylesheetPath} has no '{start.Trim()}' and '{end.Trim()}' marker pair."
            );
        }

        var block = string.Concat(
            tokens.Select(token => $"  --vibe-{token.Key}: {token.Value};\n")
        );
        return stylesheet[..(from + start.Length)] + block + stylesheet[to..];
    }

    /// <summary>
    /// Compares a checked-in file with what the definitions produce. With
    /// <see cref="UpdateVariable"/> set to true it writes the file and passes.
    /// </summary>
    internal static void AssertUpToDate(string relativePath, string expected)
    {
        var path = Path.Combine(RepositoryRoot(), relativePath);
        var actual = File.Exists(path) ? Normalize(File.ReadAllText(path)) : string.Empty;

        if (actual == expected)
        {
            return;
        }

        if (
            bool.TryParse(Environment.GetEnvironmentVariable(UpdateVariable), out var update)
            && update
        )
        {
            File.WriteAllText(path, expected);
            return;
        }

        var line = FirstDifferentLine(actual, expected);
        throw new Xunit.Sdk.XunitException(
            $"{relativePath} does not match the theme definitions in themes/. "
                + $"First difference at line {line.Number}:{Environment.NewLine}"
                + $"  on disk:   {line.Actual}{Environment.NewLine}"
                + $"  generated: {line.Expected}{Environment.NewLine}"
                + $"Edit the definition, not the generated file, then run: {RegenerateCommand}"
        );
    }

    private static (int Number, string Actual, string Expected) FirstDifferentLine(
        string actual,
        string expected
    )
    {
        var actualLines = actual.Split('\n');
        var expectedLines = expected.Split('\n');

        for (var index = 0; index < Math.Max(actualLines.Length, expectedLines.Length); index++)
        {
            var left = index < actualLines.Length ? actualLines[index] : "(end of file)";
            var right = index < expectedLines.Length ? expectedLines[index] : "(end of file)";
            if (left != right)
            {
                return (index + 1, left, right);
            }
        }

        return (0, string.Empty, string.Empty);
    }

    private static string Normalize(string text) =>
        text.Replace("\r\n", "\n", StringComparison.Ordinal);
}
