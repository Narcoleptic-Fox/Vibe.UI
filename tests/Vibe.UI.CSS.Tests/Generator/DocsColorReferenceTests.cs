using System.Text;
using System.Text.Json;
using Vibe.UI.CSS.Generator;

namespace Vibe.UI.CSS.Tests.Generator;

/// <summary>
/// The docs site's Colors page lists every palette colour and says which theme colours have
/// utilities. The docs app cannot reference this generator, so the page reads a file generated
/// here from <see cref="VibeColors"/> and <see cref="UtilityGenerator"/>. This test fails when the
/// file and the generator disagree, and writes it when asked to.
/// </summary>
public class DocsColorReferenceTests
{
    private const string UpdateVariable = "UPDATE_GENERATED_DOCS";
    private const string RelativePath = "samples/Vibe.UI.Docs/Services/ColorReference.g.cs";
    private const string RegenerateCommand =
        $"{UpdateVariable}=true dotnet test tests/Vibe.UI.CSS.Tests --filter DocsColorReference";

    [Fact]
    public void DocsColorReferenceMatchesTheGenerator()
    {
        var root = RepositoryRoot();
        var path = Path.Combine(root, RelativePath);
        var expected = Render(ThemeTokenNames(root));
        var actual = File.Exists(path)
            ? File.ReadAllText(path).Replace("\r\n", "\n")
            : string.Empty;

        if (actual == expected)
        {
            return;
        }

        if (
            bool.TryParse(Environment.GetEnvironmentVariable(UpdateVariable), out var update)
            && update
        )
        {
            File.WriteAllText(path, expected);
            return;
        }

        Assert.Fail(
            $"{RelativePath} does not match VibeColors and the utility generator. "
                + $"Edit the generator, not the generated file, then run: {RegenerateCommand}"
        );
    }

    private static string Render(IReadOnlyList<string> themeTokens)
    {
        var generator = new UtilityGenerator();
        var text = new StringBuilder();
        text.Append(
            $$"""
            // <auto-generated>
            //     Written from VibeColors and UtilityGenerator by DocsColorReferenceTests.
            //     Do not edit. To regenerate:
            //     {{RegenerateCommand}}
            // </auto-generated>
            #nullable enable

            namespace Vibe.UI.Docs.Services;

            /// <summary>
            /// The colours the utility classes produce, for the Colors page.
            /// </summary>
            internal static class ColorReference
            {
                /// <summary>Every palette family, its shades in order, and the hex each produces.</summary>
                public static readonly (string Family, (int Shade, string Hex)[] Shades)[] Palette =
                [

            """
        );

        foreach (var (family, shades) in VibeColors.Palette)
        {
            var cells = string.Join(
                ", ",
                VibeColors.ValidShades.Select(shade => $"({shade}, \"{shades[shade]}\")")
            );
            text.Append($"        (\"{family}\", [{cells}]),\n");
        }

        text.Append(
            """
                ];

                /// <summary>Theme colours that have background, text and border utilities.</summary>
                public static readonly string[] ThemeTokensWithUtilities =
                [

            """
        );

        foreach (
            var token in themeTokens.Where(token =>
                generator.Generate($"vibe-bg-{token}") is not null
            )
        )
        {
            text.Append($"        \"{token}\",\n");
        }

        text.Append(
            """
                ];
            }

            """
        );

        return text.ToString();
    }

    private static IReadOnlyList<string> ThemeTokenNames(string root)
    {
        using var document = JsonDocument.Parse(
            File.ReadAllText(Path.Combine(root, "themes", "tide.json"))
        );
        return document
            .RootElement.GetProperty("light")
            .EnumerateObject()
            .Select(token => token.Name)
            .ToArray();
    }

    private static string RepositoryRoot()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "Vibe.slnx")))
        {
            directory = directory.Parent;
        }

        return directory?.FullName
            ?? throw new InvalidOperationException("Vibe.slnx not found above the test output.");
    }
}
